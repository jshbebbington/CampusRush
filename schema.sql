CREATE TABLE players (
    player_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR2(40) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_players_display_name UNIQUE (display_name),
    CONSTRAINT ck_players_display_name CHECK (
        LENGTH(TRIM(display_name)) BETWEEN 2 AND 40
    )
);

CREATE TABLE scores (
    score_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id NUMBER NOT NULL,
    score_value NUMBER(10) NOT NULL,
    distance_value NUMBER(10) NOT NULL,
    achieved_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_scores_player FOREIGN KEY (player_id)
        REFERENCES players(player_id) ON DELETE CASCADE,
    CONSTRAINT ck_scores_score_value CHECK (score_value >= 0),
    CONSTRAINT ck_scores_distance_value CHECK (distance_value >= 0)
);

CREATE INDEX ix_scores_leaderboard
    ON scores (score_value DESC, achieved_at ASC);

CREATE INDEX ix_scores_player
    ON scores (player_id);

